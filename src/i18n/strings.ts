/** Wählt den Singular-/Pluralschlüssel (n===1 → .one, sonst .other) und interpoliert n. */
export function tPlural(baseKey: string, n: number): string {
  return t(`${baseKey}.${n === 1 ? 'one' : 'other'}`, n);
}
