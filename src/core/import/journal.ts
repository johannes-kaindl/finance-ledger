/**
 * Journal- und Kontenplan-Ausgabe im hledger-Format.
 *
 * Port der Journal-Teile von `output/ledger.py`. Die Eröffnungsbilanz
 * (`opening_balances.ledger`) hängt an den Konto-Notizen statt an den CSVs und
 * kommt deshalb erst mit E3 — sie bleibt bis dahin unverändert liegen, was
 * korrekt ist: ein CSV-Import ändert keinen Anfangssaldo.
 */

import type { ImporterContext } from "../config/context";
import type { MoneyValue } from "../money";
import {
	categorize,
	postingAccount,
	type CategorizationResult,
	type CategorizeInput,
} from "./categorize";
import type { CategorizerRules } from "./rules";
import type { BankTransaction } from "./transaction";

/**
 * Durchlaufkonto für Umbuchungen zwischen eigenen Konten.
 *
 * Bewusst **nicht** unter `Aktiva:` — es ist kein Vermögen, sondern ein
 * Durchlaufposten, und stand als `Aktiva:Umbuchung` mit über 8.000 € in der
 * Kontostandsübersicht und verfälschte deren Gesamtsumme.
 *
 * Es geht auch nicht zwingend auf null auf: decken zwei CSVs unterschiedliche
 * Zeiträume ab, fehlt für die Randbuchungen die Gegenseite. Das ist eine
 * Eigenschaft der Datenlage, kein Rechenfehler.
 */
export const CLEARING_ACCOUNT = "Verrechnung:Umbuchung";

const WHITESPACE_RUN = /\s+/g;

/** Eine Buchung mit ihrem Buchungskonto und ihrer Kategorisierung. */
export interface CategorizedTx {
	tx: BankTransaction;
	posting: string;
	result: CategorizationResult;
}

/** `-39.95 EUR` — Punkt-Notation, wie hledger sie erwartet. */
export function fmtEur(amount: MoneyValue): string {
	return `${amount.toFixed(2)} EUR`;
}

export function formatTransaction(
	tx: BankTransaction,
	postingAcct: string,
	gegenAccount: string,
	tags: readonly string[],
): string {
	const lines = [`${tx.buchungstag} * ${description(tx)}`];
	const vz = flat(tx.verwendungszweck);
	if (vz !== "") {
		lines.push(`    ; verwendungszweck: ${vz}`);
	}
	lines.push(`    ; quelle: ${tx.quelle} row ${tx.rawRowIdx}`);
	if (tags.length > 0) {
		// Alle Tags stehen auf einer Zeile zwischen Doppelpunkten — das Format,
		// das der Journal-Parser des Plugins liest.
		lines.push(`    ; :${tags.join(":")}:`);
	}
	lines.push(`    ${postingAcct}  ${fmtEur(tx.betrag)}`);
	lines.push(`    ${gegenAccount}  ${fmtEur(tx.betrag.negated())}`);
	lines.push("");
	return lines.join("\n");
}

/** Sortiert nach Datum, Quelldatei und Zeilennummer und formatiert. */
export function formatJournal(categorized: readonly CategorizedTx[]): string {
	const items = [...categorized].sort(
		(a, b) =>
			compare(a.tx.buchungstag, b.tx.buchungstag) ||
			compare(a.tx.quelle, b.tx.quelle) ||
			a.tx.rawRowIdx - b.tx.rawRowIdx,
	);
	const parts = [
		"; Generated by finanzplan-importer",
		"; journal.ledger — alle Buchungen aus den 4 Sparkasse-CSVs",
		"",
	];
	for (const item of items) {
		parts.push(
			formatTransaction(
				item.tx,
				item.posting,
				item.result.gegenAccount,
				item.result.tags,
			),
		);
	}
	return parts.join("\n");
}

