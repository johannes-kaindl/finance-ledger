export function formatAccounts(
	ctx: ImporterContext,
	rules: CategorizerRules,
	signRuleAccounts: readonly string[] = [],
): string {
	const accounts = new Set<string>([
		...STATIC_ACCOUNTS,
		...CATEGORIZER_ACCOUNTS,
		...signRuleAccounts,
		// Die konfigurierten Bankkonten selbst — sonst fehlt genau das Konto,
		// das der Nutzer gerade neu angelegt hat.
		...ctx.activeKonten.map((k) => k.ledgerAccount),
		...rules.counterparty.map((r) => r.ledgerAccount),
		...rules.paypal.map((r) => r.ledgerAccount),
	]);

	const lines = [
		"; Generated by finanzplan-importer",
		"; accounts.ledger — Konten-Plan (Foundation §2)",
		"",
		...[...accounts].sort().map((a) => `account ${a}`),
		"",
	];
	return lines.join("\n");
}

/**
 * Bucht Umbuchungen zwischen eigenen Konten über das Verrechnungskonto.
 *
 * Eine Umbuchung steht in **beiden** Kontoauszügen: einmal als Abgang beim
 * Quellkonto, einmal als Eingang beim Zielkonto. Wer aus jeder Zeile die
 * vollständige Transaktion samt Gegenseite bucht, bewegt beide Konten um den
 * doppelten Betrag.
 *
 * Ein Paarabgleich über Datum, Betrag und Kontenpaar scheitert an der Praxis:
 * die Kreditkartenabrechnung steht im Kartenauszug am 02., im Girokontoauszug
 * am 05. Ein Toleranzfenster wiederum verschmilzt zwei echte Umbuchungen
 * gleichen Betrags innerhalb der Frist.
 *
 * Deshalb strukturell: **jede Bankzeile bucht nur ihr eigenes Konto**, die
 * Gegenseite läuft übers Verrechnungskonto. Beide Seiten treffen sich dort und
 * heben sich auf. Kein Abgleich, keine Datumsannahme, und jede Bankzeile bleibt
 * einzeln nachvollziehbar.
 *
 * Nur wenn das Gegenkonto **selbst eine CSV liefert**, kommt die zweite Sicht
 * überhaupt. Sonst muss direkt aufs Zielkonto gebucht werden — andernfalls
 * bekäme es seine Bewegung nie und im Durchlaufkonto bliebe der Betrag liegen.
 */
export function routeSelfTransfersViaClearing(
	categorized: readonly CategorizedTx[],
	importedAccounts: ReadonlySet<string>,
): CategorizedTx[] {
	return categorized.map((item) => {
		const isSelfTransfer = item.result.tags.includes("self-transfer");
		if (
			isSelfTransfer &&
			importedAccounts.has(item.result.gegenAccount) &&
			item.result.gegenAccount !== CLEARING_ACCOUNT
		) {
			return {
				...item,
				result: { ...item.result, gegenAccount: CLEARING_ACCOUNT },
			};
		}
		return item;
	});
}

/** Buchungen kategorisieren und Umbuchungen übers Verrechnungskonto leiten. */
export function categorizeAll(
	transactions: readonly BankTransaction[],
	input: CategorizeInput,
): CategorizedTx[] {
	const categorized = transactions.map((tx) => ({
		tx,
		posting: postingAccount(tx, input.ctx),
		result: categorize(tx, input),
	}));
	return routeSelfTransfersViaClearing(
		categorized,
		input.ctx.importedLedgerAccounts,
	);
}

function description(tx: BankTransaction): string {
	const raw =
		tx.beguenstigter.trim() || tx.buchungstext.trim() || "(unbekannt)";
	return flat(raw);
}

/** Zeilenumbrüche und Mehrfach-Leerzeichen zu einem Leerzeichen. */
function flat(value: string): string {
	return value.replace(WHITESPACE_RUN, " ").trim();
}

function compare(a: string, b: string): number {
	return a < b ? -1 : a > b ? 1 : 0;
}
