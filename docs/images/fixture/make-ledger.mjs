/**
 * Erzeugt `journal.ledger`, `accounts.ledger` und `opening_balances.ledger` des
 * Aufnahme-Vaults — **relativ zum heutigen Datum**.
 *
 * Warum als Generator und nicht als abgelegte Datei: das Dashboard zeigt eine Karte
 * „Top 3 categories (current month)". Mit festen Daten im Fixture ist sie ab dem
 * Folgemonat leer, und das Bild dokumentiert dann einen Leerzustand statt der Funktion —
 * gemessen beim ersten Lauf am 2026-08-17, dessen Fixture im Juni endete.
 *
 * Aufruf durch `buildVault` (`VaultSpec.generator`): `node make-ledger.mjs <vaultDir>`.
 */

import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { argv } from "node:process";

const vaultDir = argv[2];
if (!vaultDir) {
  throw new Error("Aufruf: node make-ledger.mjs <vaultDir>");
}

const KONTEN = {
  checking: ["GB00ACME00000001", "Aktiva:Bank:Everyday Checking", "2480.00"],
  pool: ["GB00ACME00000002", "Aktiva:Bank:Household Pool", "940.00"],
  visa: ["GB00ACME00000003", "Passiva:Credit Card:Everyday Visa", "-320.00"],
};

/** Ein Monatsmuster; `tag` ist der Kalendertag, `monat` der Versatz zum aktuellen. */
const MUSTER = [
  [1, "Globex Corporation", "3200.00", "Einnahmen:Salary:Globex", "checking", ":recurring:", "Salary"],
  [2, "Acme Power", "-96.40", "Ausgaben:Utilities:Acme Power", "checking", ":recurring:", "Electricity"],
  [3, "Northwind Grocers", "-64.12", "Ausgaben:Groceries:Northwind", "checking", "", "Card payment"],
  [5, "Metro Transit", "-59.00", "Ausgaben:Transport:Metro Transit", "checking", ":recurring:", "Monthly pass"],
  [7, "Initech Streaming", "-12.99", "Ausgaben:Subscriptions:Streaming", "visa", ":recurring:", "Subscription"],
  [9, "Northwind Grocers", "-81.55", "Ausgaben:Groceries:Northwind", "checking", "", "Card payment"],
  [11, "Umbrella Insurance", "-142.00", "Ausgaben:Insurance:Umbrella", "checking", ":recurring:", "Household policy"],
  [12, "Soylent Cafe", "-18.40", "Ausgaben:Dining:Soylent Cafe", "visa", "", "Lunch"],
  [15, "Wayne Hardware", "-233.90", "Ausgaben:Household:Wayne Hardware", "pool", "", "Shelving"],
  [16, "Northwind Grocers", "-72.30", "Ausgaben:Groceries:Northwind", "checking", "", "Card payment"],
  [18, "Stark Fitness", "-39.00", "Ausgaben:Health:Stark Fitness", "visa", ":recurring:", "Membership"],
  [20, "Cyberdyne Telecom", "-44.99", "Ausgaben:Communication:Cyberdyne", "checking", ":recurring:", "Broadband"],
  [22, "Tyrell Books", "-27.80", "Ausgaben:Leisure:Tyrell Books", "visa", "", "Paperbacks"],
  [24, "Northwind Grocers", "-91.05", "Ausgaben:Groceries:Northwind", "checking", "", "Card payment"],
  [28, "Gringotts Rent", "-1150.00", "Ausgaben:Housing:Rent", "checking", ":recurring:", "Rent"],
];

/** Buchungen ohne Zuordnung — sie füllen die Triage-Ansicht. */
const OFFEN = [
  [-2, 26, "Vandelay Imports", "-58.20", "visa", "Card payment 4711"],
  [-1, 8, "Oscorp Repairs", "-410.00", "pool", "Invoice 88213"],
  [-1, 15, "Hooli Cloud", "-9.99", "visa", "HOOLI*CLOUD 88213"],
  [0, 9, "Pied Piper Storage", "-24.00", "visa", "PP-STORAGE 5521"],
];

const heute = new Date();
const iso = (monatsVersatz, tag) => {
  const d = new Date(heute.getFullYear(), heute.getMonth() + monatsVersatz, tag);
  const p = (n) => String(n).padStart(2, "0");
  return `${d.getFullYear()}-${p(d.getMonth() + 1)}-${p(d.getDate())}`;
};

const buchungen = [];
// Drei Monate: vorletzter, letzter, laufender. Im laufenden Monat nur, was schon war —
// ein Kontoauszug mit Buchungen aus der Zukunft sieht nach einem Fehler aus.
for (const versatz of [-2, -1, 0]) {
  for (const [tag, wer, betrag, gegen, konto, tags, zweck] of MUSTER) {
    if (versatz === 0 && tag > heute.getDate()) continue;
    buchungen.push({ datum: iso(versatz, tag), wer, betrag, gegen, konto, tags, zweck });
  }
}
for (const [versatz, tag, wer, betrag, konto, zweck] of OFFEN) {
  if (versatz === 0 && tag > heute.getDate()) continue;
  buchungen.push({ datum: iso(versatz, tag), wer, betrag, gegen: "", konto, tags: ":tbc:", zweck });
}
buchungen.sort((a, b) => a.datum.localeCompare(b.datum));

const zeilen = ["; Generated by finance-ledger-importer (fixture)", ""];
buchungen.forEach((b, i) => {
  const [iban, ledger] = KONTEN[b.konto];
  const ziel = b.gegen || "Ausgaben:Unassigned";
  const gegenbetrag = b.betrag.startsWith("-") ? b.betrag.slice(1) : `-${b.betrag}`;
  zeilen.push(`${b.datum} * ${b.wer}`);
  zeilen.push(`    ; verwendungszweck: ${b.zweck}`);
  zeilen.push(`    ; quelle: ${b.datum.replace(/-/g, "")}-${iban.slice(-4)}-camt52v8.CSV row ${i + 2}`);
  if (b.tags) zeilen.push(`    ; ${b.tags}`);
  zeilen.push(`    ${ledger}  ${b.betrag} EUR`);
  zeilen.push(`    ${ziel}  ${gegenbetrag} EUR`);
  zeilen.push("");
});

const ledgerDir = join(vaultDir, "Finance", "Ledger");
mkdirSync(ledgerDir, { recursive: true });
writeFileSync(join(ledgerDir, "journal.ledger"), zeilen.join("\n"));

const konten = [
  ...new Set([
    ...buchungen.map((b) => b.gegen).filter(Boolean),
    ...Object.values(KONTEN).map(([, ledger]) => ledger),
    "Ausgaben:Unassigned",
    "Eigenkapital:Eroeffnungsbilanz",
  ]),
].sort();
writeFileSync(
  join(ledgerDir, "accounts.ledger"),
  `; Generated by finance-ledger-importer (fixture)\n\n${konten.map((a) => `account ${a}`).join("\n")}\n`,
);

// Eröffnungsstichtag: der Erste des ersten dargestellten Monats.
const stichtag = iso(-2, 1);
const namen = {
  checking: "Account 01 – Everyday Checking",
  pool: "Account 02 – Household Pool",
  visa: "Account 03 – Everyday Visa",
};
const opening = ["; Generated by finance-ledger-importer (fixture)", ""];
for (const [key, [, ledger, saldo]] of Object.entries(KONTEN)) {
  const gegen = saldo.startsWith("-") ? saldo.slice(1) : `-${saldo}`;
  opening.push(`${stichtag} * Opening balance ${namen[key]}`);
  opening.push(`    ${ledger}  ${saldo} EUR`);
  opening.push(`    Eigenkapital:Eroeffnungsbilanz  ${gegen} EUR`);
  opening.push("");
}
writeFileSync(join(ledgerDir, "opening_balances.ledger"), opening.join("\n"));

// Die Konto-Notizen tragen den Stichtag im Frontmatter — er muss mitwandern.
console.log(
  `journal.ledger: ${buchungen.length} Buchungen (${buchungen[0].datum} … ${buchungen.at(-1).datum}), Stichtag ${stichtag}`,
);
